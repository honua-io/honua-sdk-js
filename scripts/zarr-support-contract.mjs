import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const fixture = new URL("conformance/zarr/support-matrix.v1.json", root);
const target = new URL("src/zarr/support-contract.ts", root);
const bytes = readFileSync(process.env.HONUA_ZARR_SUPPORT_MATRIX ?? fixture);
const matrix = JSON.parse(bytes.toString("utf8"));
if (matrix.format !== "honua.zarr-support/v1" || !Array.isArray(matrix.cells) || matrix.cells.length === 0) {
  throw new Error("Unsupported or empty Zarr support contract");
}
const unique = (values) => [...new Set(values)];
const rows = unique(matrix.cells.map((cell) => JSON.stringify([cell.version, cell.dataType, cell.normalizedDataType])));
const codecs = unique(matrix.cells.map((cell) => JSON.stringify([cell.version, cell.codec])));
const output = [
  '// Generated by scripts/zarr-support-contract.mjs from the versioned server contract.',
  `export const ZARR_SUPPORT_FORMAT = ${JSON.stringify(matrix.format)};`,
  'export const ZARR_SUPPORT_DATA_TYPES: readonly (readonly [number, string, string])[] = [',
  ...rows.map((row) => `  ${row},`),
  '];',
  'export const ZARR_SUPPORT_CODECS: readonly (readonly [number, string])[] = [',
  ...codecs.map((row) => `  ${row},`),
  '];',
  '',
].join("\n");
if (process.argv.includes("--write")) {
  writeFileSync(fixture, bytes);
  writeFileSync(target, output);
} else {
  if (!bytes.equals(readFileSync(fixture)) || output !== readFileSync(target, "utf8")) {
    throw new Error(`Zarr support projection drift: run node ${fileURLToPath(import.meta.url)} --write against the canonical contract`);
  }
}
